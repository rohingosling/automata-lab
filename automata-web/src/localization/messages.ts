//--------------------------------------------------------------------------------------------------
// Type: MessageKey
//
// Description:
//
//   Defines the message key type.
//
//--------------------------------------------------------------------------------------------------

export type MessageKey = keyof typeof ENGLISH_MESSAGES;

//--------------------------------------------------------------------------------------------------
// Type: SupportedLocale
//
// Description:
//
//   Defines the supported locale type.
//
//--------------------------------------------------------------------------------------------------

export type SupportedLocale = "en";

const LOCALIZED_MESSAGES: Readonly <Record <SupportedLocale, Readonly <Record <MessageKey, string>>>> =
{
    en: ENGLISH_MESSAGES,
};


//--------------------------------------------------------------------------------------------------
// Function: resolveLocale
//
// Description:
//
//   Resolves locale.
//
// Parameters:
//
//   - locale:
//     The locale supplied to the operation.
//
// Returns:
//
//   The value produced by the operation.
//
// Preconditions:
//
//   - The supplied arguments satisfy their declared TypeScript contracts.
//
// Postconditions:
//
//   - The returned value represents the result described above.
//
//--------------------------------------------------------------------------------------------------

export function resolveLocale ( locale: string | undefined ): SupportedLocale
{
    // Return the result selected by the current condition.

    return locale?.toLocaleLowerCase ().startsWith ( "en" ) ? "en" : "en";
}


//--------------------------------------------------------------------------------------------------
// Function: text
//
// Description:
//
//   Derives the text.
//
// Parameters:
//
//   - key:
//     The key supplied to the operation.
//
//   - locale:
//     The locale supplied to the operation.
//
// Returns:
//
//   The value produced by the operation.
//
// Preconditions:
//
//   - The supplied arguments satisfy their declared TypeScript contracts.
//
// Postconditions:
//
//   - The returned value represents the result described above.
//
//--------------------------------------------------------------------------------------------------

export function text ( key: MessageKey, locale: string | undefined = "en" ): string
{
    // Initialize the local values needed by this operation.

    const messages = LOCALIZED_MESSAGES [ resolveLocale ( locale ) ];


    // Return the computed result.

    return messages [ key ] ?? ENGLISH_MESSAGES [ key ] ?? key;
}
