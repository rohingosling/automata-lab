import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory  = dirname ( fileURLToPath ( import.meta.url ) );
const packageDirectory = dirname ( scriptDirectory );
const schemaPath       = join ( packageDirectory, "public", "schema", "automata-lab-state-machine-1.3.0.schema.json" );
const outputPath       = join (
    packageDirectory,
    "src",
    "infrastructure",
    "files",
    "generated",
    "file-schema-v1-validator.js",
);
const checkOnly = process.argv.includes ( "--check" );

//--------------------------------------------------------------------------------------------------
// Function: generateValidator
//
// Description:
//
//   Generates the validator.
//
// Parameters:
//
//   - schema:
//     The schema supplied to the operation.
//
// Returns:
//
//   The value produced by the operation.
//
// Preconditions:
//
//   - The supplied arguments satisfy their declared TypeScript contracts.
//
// Postconditions:
//
//   - The returned value represents the result described above.
//
//--------------------------------------------------------------------------------------------------

function generateValidator ( schema )
{
    // Initialize the local values needed by this operation.

    const ajv = new Ajv2020 (
        {
            allErrors: true,
            inlineRefs: false,
            code:
            {
                esm:    true,
                lines:  true,
                source: true,
            },
            strict: true,
        },
    );
    const validator              = ajv.compile ( schema );
    const generatedSource        = standaloneCode ( ajv, validator );
    const runtimeHelperStatement = 'const func1 = require("ajv/dist/runtime/ucs2length").default;';

    // Handle the case where the includes result condition is not satisfied.

    if ( !generatedSource.includes ( runtimeHelperStatement ) )
    {
        throw new Error ( "The Ajv standalone helper shape changed; review the generated validator before updating it." );
    }

    // Calculate the browser source value from the current inputs.

    const browserSource = generatedSource.replace (
        runtimeHelperStatement,
        "function unicodeCodePointLength ( value ) { return [ ...value ].length; }\n" +
            "const func1 = unicodeCodePointLength;",
    );

    // Handle the case where at least one branch condition is satisfied.

    if ( /\brequire\s*\(/u.test ( browserSource ) || /\b(?:eval|Function)\s*\(/u.test ( browserSource ) )
    {
        throw new Error ( "The standalone schema validator contains a forbidden dynamic-code construct." );
    }

    // Return the join result.

    return [
        "// This file is generated by scripts/generate-schema-validator.mjs. Do not edit it by hand.",
        browserSource.trim (),
        "",
    ].join ( "\n" );
}

// Shares only structurally identical bounded records. Public schemas remain independently readable.
// Keeping references out of schema conditions preserves version dispatch and diagnostic ordering.

function shareRepeatedSchemaRecords ( schema )
{
    const stateMachine = schema.properties.state_machine.properties;
    const draftTransition = schema.properties.chart.properties.draft_transitions.items.properties;
    const namedEntity = stateMachine.events.items;
    const definitions = {
        generatedNamedEntity: namedEntity,
        generatedStateActionMapping: stateMachine.state_actions.properties.entry.items,
        generatedChartPoint: draftTransition.source,
        generatedBoundedName: namedEntity.properties.name,
        generatedDescription: namedEntity.properties.description,
        generatedNullableName: draftTransition.source_state,
        generatedSafeIdentifier: schema.properties.chart.properties.draft_transitions.items.properties.id,
    };
    const identifiersBySchema = new Map ( Object.entries ( definitions ).map ( ( [ name, definition ] ) =>
        [ JSON.stringify ( definition ), name ] ) );
    const share = ( value, isDefinitionRoot = false ) =>
    {
        if ( value === null || typeof value !== "object" )
        {
            return value;
        }
        if ( Array.isArray ( value ) )
        {
            return value.map ( item => share ( item ) );
        }
        const identifier = identifiersBySchema.get ( JSON.stringify ( value ) );
        if ( identifier !== undefined && !isDefinitionRoot )
        {
            return { $ref: "#/$defs/" + identifier };
        }
        return Object.fromEntries ( Object.entries ( value ).map ( ( [ name, member ] ) => [ name, share ( member ) ] ) );
    };
    const sharedSchema = share ( schema );
    sharedSchema.$defs = {
        ...sharedSchema.$defs,
        ...Object.fromEntries ( Object.entries ( definitions ).map ( ( [ name, definition ] ) =>
            [ name, share ( definition, true ) ] ) ),
    };
    return sharedSchema;
}

const schema         = JSON.parse ( await readFile ( schemaPath, "utf8" ) );
// Share validation code while preserving each earlier version's exact property boundary.

schema.properties.file_version = { enum: [ "1.0.0", "1.1.0", "1.2.0", "1.3.0" ] };
schema.allOf = [
    { versions: [ "1.0.0" ], forbidden: { source_state: false, target_state: false } },
    { versions: [ "1.0.0", "1.1.0", "1.2.0" ], forbidden: { source_indicator: false, target_indicator: false } },
    { versions: [ "1.0.0", "1.1.0" ], forbidden: { remembered_event: false, remembered_transition_index: false } },
].map ( ( { versions, forbidden } ) => ( {
    if: { properties: { file_version: { enum: versions } } },
    then:
    {
        properties:
        {
            chart:
            {
                type: "object",
                properties:
                {
                    draft_transitions:
                    {
                        type: "array",
                        items: { type: "object", properties: forbidden },
                    },
                },
            },
        },
    },
} ) );
schema.allOf.push ( {
    if: { properties: { file_version: { enum: [ "1.0.0", "1.1.0", "1.2.0" ] } } },
    then: { properties: { chart: { type: "object", properties: { indicators: {
        type: "object", properties: { indicator_transitions: false },
    } } } } },
} );
const expectedSource = generateValidator ( shareRepeatedSchemaRecords ( schema ) );

if ( checkOnly )
{
    let currentSource;

    try
    {
        currentSource = await readFile ( outputPath, "utf8" );
    }
    catch
    {
        throw new Error ( "The committed standalone schema validator is missing; run npm run schema:generate." );
    }

    if ( currentSource.replaceAll ( "\r\n", "\n" ) !== expectedSource )
    {
        throw new Error ( "The standalone schema validator is stale; run npm run schema:generate and review it." );
    }

    console.log ( "Verified the CSP-safe standalone schema validator." );
}
else
{
    await mkdir ( dirname ( outputPath ), { recursive: true } );
    await writeFile ( outputPath, expectedSource, "utf8" );
    console.log ( "Generated the CSP-safe standalone schema validator." );
}
